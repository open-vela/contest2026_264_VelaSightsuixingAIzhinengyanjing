/* GC2145 is at 7-bit I2C address 0x3C (datasheet's 0x78 write / 0x79 read
 * are the pre-shifted 8-bit forms; bk7258_i2c1_write_reg() takes the
 * 7-bit form and performs the <<1 shift internally -- see
 * bk7258_gc2145_i2c_bitbang.h). */
#define GC2145_I2C_ADDR      0x3Cu

/* DVP data/sync pins, per design doc section 2 (gpio_map.h
 * CAMERA_DVP_*_PIN macros) and Task 3 background verification: all of
 * MCLK/PCLK/HSYNC/VSYNC/PXDATA0-7 sit at pinmux function index 0 in their
 * respective gpio_map_table per-pin function arrays. */
#define DVP_MCLK_PIN         27u
#define DVP_PCLK_PIN         29u
#define DVP_HSYNC_PIN        30u
#define DVP_VSYNC_PIN        31u
#define DVP_DATA_PIN(i)      (32u + (i))
#define DVP_PINMUX_FUNCTION  0u

/* Camera reset and power-enable GPIOs, corrected against the actual
 * board schematic (AIDK_AI玩具开发板_原理图.pdf) after this driver's
 * first two hardware bring-up attempts both failed with the GC2145 never
 * ACKing the first I2C write (register 0xFE).  This driver's original
 * assumption -- ported from a *different* board's reference config
 * (bk_avdk_smp release/v3.1.1
 * projects/dvp_example/ap/config/bk7258_ap/config
 * CONFIG_DVP_CTRL_POWER_GPIO_ID=28) -- was that GPIO28 is a power-enable
 * pin.  The schematic (sheet 2/6 chip pin table) shows GPIO28's net label
 * is actually DVP_RST (wired to the DVP connector's pin 7 RST signal,
 * sheet 4/6), not power.
 *
 * The real power-enable signal is DVP_PWR_CTL, which the schematic shows
 * driven from GPIO49 (sheet 2/6: net label DVP_PWR_CTL sits at physical
 * pin 88, which the same sheet's main pin table identifies as
 * P49/ENET_RXD0/R1/D17). DVP_PWR_CTL simultaneously enables two LDOs on
 * sheet 3/6 ("DVP供电" section): U4 (ME6211C28M5G-N) producing the
 * camera's +2.8V analog supply, and U5 (RS3236-ADJ8YF5) producing an
 * adjustable DVDD whose feedback divider (R28=75K) is annotated
 * "1.8V 75K" -- i.e. this board's DVDD rail is already hardwired for
 * GC2145's documented 1.8V DVDD requirement (the same sheet 4/6 comment
 * block that lists "GC2145: 1.8V" alongside GC2053's 1.2V and HM1055's
 * 1.5V for the same connector, confirming this board's fixed divider was
 * chosen for GC2145 specifically). */
#define DVP_RESET_PIN        28u
#define DVP_POWER_PIN        49u

#define GC2145_CAPTURE_WIDTH   640u
#define GC2145_CAPTURE_HEIGHT  480u


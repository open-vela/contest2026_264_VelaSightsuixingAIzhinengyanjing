/****************************************************************************
 * board/beken/boards/bk7258/bk7258-ap/src/bk7258_gc2145.c
 *
 * GC2145 CMOS sensor bring-up: I2C init register table copied verbatim
 * from bk_avdk_smp release/v3.1.1
 * ap/components/bk_peripheral/src/dvp/dvp_gc2145.c
 * (sensor_gc2145_init_talbe: 585 entries, sensor_gc2145_640_480_table: 40
 * entries; both tables extracted programmatically via a Python script
 * that parses the {0xXX, 0xXX} pairs directly from the source file to
 * avoid manual-transcription errors, skipping the #if 0/#endif-guarded
 * 50Hz frame-rate block in sensor_gc2145_init_talbe that upstream itself
 * does not compile in).  YUV direct-capture only; no JPEG/H264 encoding,
 * fixed at 640x480 (no runtime resolution switching).
 *
 * This bring-up milestone deliberately does not implement full-frame
 * assembly: YUV_BUF's hardware line buffer only holds 8 lines at a time
 * (ping-pong), and a full 640x480 frame requires 60 consecutive line-done
 * interrupts with a running destination offset to assemble.  This test
 * only verifies the first line-done interrupt fires and its 8 lines
 * (10240 bytes = 640*8*2, YUV422) can be DMA-copied out of the PSRAM line
 * buffer -- see docs/superpowers/plans/2026-07-30-gc2145-camera-bringup.md
 * "background section" for the full architectural rationale and the
 * decision to scope this milestone down to a single line-done event
 * rather than full-frame capture.
 *
 * SPDX-License-Identifier: Apache-2.0
 ****************************************************************************/


static volatile bool g_line_ready;

static void bk7258_gc2145_power_on(void)
{
  bk7258_gpio_output(DVP_POWER_PIN, true);

  /* Settle delay after enabling the camera's two LDOs (+2.8V AVDD and
   * 1.8V DVDD, sheet 3/6) before any reset/I2C traffic; GC2145 datasheet
   * power-up timing is not available in this repo, so this uses the same
   * 120ms convention already established for GC9D01 hardware-reset
   * settling (docs/superpowers/plans/2026-07-29-gc9d01-lcd-bringup.md
   * Task 3, citing multiple bk_avdk_smp LCD drivers' uniform 120ms
   * post-reset delay) as a conservative, cross-checked default rather
   * than an unverified guess. */
  up_udelay(120000);
}

static void bk7258_gc2145_reset(void)
{
  /* DVP_RST (GPIO28) is active-low on the DVP connector's pin 7 RST
   * signal (schematic sheet 4/6): assert (drive low), hold, then
   * release (drive high) before I2C traffic, rather than this driver's
   * previous mistake of holding GPIO28 permanently high as if it were a
   * power-enable pin (see DVP_RESET_PIN's definition comment for the
   * schematic evidence behind this correction). Hold times are not in
   * this repo's GC2145 datasheet excerpt, so this reuses the same 120ms
   * conservative settling convention as bk7258_gc2145_power_on(). */
  bk7258_gpio_output(DVP_RESET_PIN, false);
  up_udelay(120000);
  bk7258_gpio_output(DVP_RESET_PIN, true);
  up_udelay(120000);
}

static void bk7258_gc2145_dvp_pinmux(void)
{
  uint32_t i;

  bk7258_gpio_set_function(DVP_MCLK_PIN, DVP_PINMUX_FUNCTION);
  bk7258_gpio_set_function(DVP_PCLK_PIN, DVP_PINMUX_FUNCTION);
  bk7258_gpio_set_function(DVP_HSYNC_PIN, DVP_PINMUX_FUNCTION);
  bk7258_gpio_set_function(DVP_VSYNC_PIN, DVP_PINMUX_FUNCTION);

  for (i = 0; i < 8; i++)
    {
      bk7258_gpio_set_function(DVP_DATA_PIN(i), DVP_PINMUX_FUNCTION);
    }
}

static bool bk7258_gc2145_write_reg_table(const struct gc2145_reg *table,
                                           size_t count)
{
  size_t i;

  for (i = 0; i < count; i++)
    {
      if (!bk7258_i2c1_write_reg(GC2145_I2C_ADDR, table[i].reg,
                                 table[i].value))
        {
          printf("gc2145: i2c write failed at reg 0x%02x (index %u)\n",
                 table[i].reg, (unsigned int)i);
          return false;
        }
    }

  return true;
}

static void bk7258_gc2145_line_done(bk7258_yuv_buf_bank_t bank, void *arg)
{
  (void)bank;
  (void)arg;
  g_line_ready = true;
}

int bk7258_gc2145_test(int argc, char **argv)
{
  uint32_t line_buf_addr;

  printf("gc2145: camera power on (GPIO%u)\n", DVP_POWER_PIN);
  bk7258_gc2145_power_on();

  printf("gc2145: camera reset (GPIO%u)\n", DVP_RESET_PIN);
  bk7258_gc2145_reset();

  printf("gc2145: dvp pinmux\n");
  bk7258_gc2145_dvp_pinmux();

  printf("gc2145: i2c1 init\n");
  bk7258_i2c1_init();

  printf("gc2145: writing %u init registers\n",
         (unsigned int)GC2145_INIT_REG_COUNT);
  if (!bk7258_gc2145_write_reg_table(g_gc2145_init_regs,
                                     GC2145_INIT_REG_COUNT))
    {
      printf("gc2145: init sequence aborted\n");
      return -1;
    }

  printf("gc2145: writing %u resolution (640x480) registers\n",
         (unsigned int)GC2145_640_480_REG_COUNT);
  if (!bk7258_gc2145_write_reg_table(g_gc2145_640_480_regs,
                                     GC2145_640_480_REG_COUNT))
    {
      printf("gc2145: resolution config aborted\n");
      return -1;
    }

  printf("gc2145: yuv_buf init\n");
  bk7258_yuv_buf_init();
  bk7258_yuv_buf_configure(GC2145_CAPTURE_WIDTH, GC2145_CAPTURE_HEIGHT);
  /* Note: this legacy smoke-test entry point only drains a single line
   * batch (whichever bank fires first) as a minimal "does the hardware
   * path work at all" check; it does not assemble a full frame -- that
   * logic now lives in bk7258_camera_imgdata.c's standard V4L2 driver
   * path, which this function intentionally does not duplicate. */
  bk7258_yuv_buf_set_line_callback(bk7258_gc2145_line_done, NULL);

  line_buf_addr = bk7258_yuv_buf_get_line_buf_addr();
  printf("gc2145: yuv_buf line buffer at 0x%08x\n",
         (unsigned int)line_buf_addr);

  printf("gc2145: dma init\n");
  bk7258_dma_init();

  printf("gc2145: starting capture\n");
  bk7258_yuv_buf_start();

  {
    int waited_ms = 0;
    const int max_wait_ms = 5000;

    while (!g_line_ready && waited_ms < max_wait_ms)
      {
        up_udelay(10000);
        waited_ms += 10;
      }
  }

  if (!g_line_ready)
    {
      printf("gc2145: timed out waiting for first line-done interrupt\n");
      bk7258_yuv_buf_stop();
      return -1;
    }

  printf("gc2145: line-done interrupt received, copying %u bytes via DMA\n",
         (unsigned int)GC2145_LINE_BATCH_BYTES);

  memset(g_gc2145_line_buf, 0, sizeof(g_gc2145_line_buf));
  bk7258_dma_configure(line_buf_addr, (uint32_t)(uintptr_t)g_gc2145_line_buf,
                       GC2145_LINE_BATCH_BYTES);
  bk7258_dma_start();

  {
    int waited_ms = 0;
    const int max_wait_ms = 1000;

    while (bk7258_dma_is_busy() && waited_ms < max_wait_ms)
      {
        up_udelay(1000);
        waited_ms += 1;
      }
  }

  if (bk7258_dma_is_busy())
    {
      printf("gc2145: dma timed out, remain_len=%u\n",
             (unsigned int)bk7258_dma_get_remain_len());
      bk7258_yuv_buf_stop();
      return -1;
    }

  printf("gc2145: dma completed, remain_len=%u\n",
         (unsigned int)bk7258_dma_get_remain_len());

  bk7258_yuv_buf_stop();

  printf("gc2145: capture test completed\n");
  return 0;
}
